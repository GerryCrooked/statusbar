#!/usr/bin/env python3
"""Regenerates docs/nav.json from the front matter of docs/de/*.md and docs/en/*.md and checks
that every relative link and anchor in those pages exists and that each page has its translation.

    python3 scripts/docs-nav.py          # writes docs/nav.json, exits 1 on broken links
    python3 scripts/docs-nav.py --check  # only checks, fails if nav.json is out of date
"""
import json
import os
import re
import sys

DOCS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs")
LANGS = ["de", "en"]
RAW = "https://raw.githubusercontent.com/GerryCrooked/statusbar/main/docs/<path>"


def front_matter(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        sys.exit(f"{path}: no front matter")
    data = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        data[key.strip()] = value.strip()
    return data, text[m.end():]


def slug(heading):
    """GitHub-style anchor of a heading."""
    heading = re.sub(r"[`*]", "", heading).strip().lower()
    return re.sub(r"[^\w\- ]", "", heading, flags=re.U).replace(" ", "-")


def main():
    pages, anchors = {}, {}
    for lang in LANGS:
        for name in sorted(os.listdir(os.path.join(DOCS, lang))):
            if not name.endswith(".md"):
                continue
            rel = f"{lang}/{name}"
            data, body = front_matter(os.path.join(DOCS, rel))
            for key in ("id", "title", "description", "lang", "slug", "order"):
                if key not in data:
                    sys.exit(f"{rel}: front matter lacks '{key}'")
            pages[rel] = (data, body)
            prose = re.sub(r"```.*?```", "", body, flags=re.S)
            anchors[rel] = {slug(h) for h in re.findall(r"^#{1,6} (.+)$", prose, re.M)}

    errors = []
    for rel, (data, body) in pages.items():
        prose = re.sub(r"```.*?```", "", body, flags=re.S)
        for target in re.findall(r"\]\(([^)]+)\)", prose):
            if re.match(r"[a-z]+:", target):
                continue
            file, _, anchor = target.partition("#")
            dest = os.path.normpath(os.path.join(os.path.dirname(rel), file)) if file else rel
            if dest not in anchors:
                errors.append(f"{rel}: link to missing page {target}")
            elif anchor and anchor not in anchors[dest]:
                errors.append(f"{rel}: link to missing heading {target}")
    by_id = {}
    for rel, (data, _) in pages.items():
        by_id.setdefault(data["id"], {})[data["lang"]] = rel
    for page_id, langs in by_id.items():
        for lang in LANGS:
            if lang not in langs:
                errors.append(f"page '{page_id}' has no {lang} version")

    nav = {"$comment": f"Generated by scripts/docs-nav.py from the front matter. Raw file: {RAW}", "languages": {}}
    for lang in LANGS:
        items = [
            {
                "id": d["id"],
                "order": int(d["order"]),
                "slug": d["slug"],
                "title": d["title"],
                "description": d["description"],
                "path": rel,
            }
            for rel, (d, _) in pages.items()
            if d["lang"] == lang
        ]
        nav["languages"][lang] = sorted(items, key=lambda x: x["order"])
    text = json.dumps(nav, ensure_ascii=False, indent=2) + "\n"
    target = os.path.join(DOCS, "nav.json")
    if "--check" in sys.argv:
        if not os.path.exists(target) or open(target, encoding="utf-8").read() != text:
            errors.append("docs/nav.json is out of date: run scripts/docs-nav.py")
    else:
        open(target, "w", encoding="utf-8").write(text)

    for e in errors:
        print(e)
    print(f"{len(pages)} pages, {len(errors)} problems")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
